namespace Listenarr.Tests.Common;

/// <summary>
/// A clock the test drives by hand. Microsoft.Extensions.TimeProvider.Testing is not referenced
/// here, and this had already been hand-rolled privately in two test classes before a third wanted
/// it, so it lives in one place rather than three.
/// </summary>
public sealed class MutableTimeProvider(DateTimeOffset utcNow) : TimeProvider
{
    private DateTimeOffset _utcNow = utcNow;

    public override DateTimeOffset GetUtcNow() => _utcNow;

    public void Advance(TimeSpan duration) => _utcNow += duration;
}
